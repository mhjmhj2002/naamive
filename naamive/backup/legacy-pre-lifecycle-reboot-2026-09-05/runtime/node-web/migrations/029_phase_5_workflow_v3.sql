-- F5-10: publish an immutable successor to PROJECT_DISCOVERY v2.  Existing
-- definitions and projects remain untouched; only projects that leave intake
-- after this publication select version 3.
ALTER TABLE operations ADD COLUMN IF NOT EXISTS workflow_code text;
ALTER TABLE operations ADD COLUMN IF NOT EXISTS workflow_version integer;
ALTER TABLE operations ADD CONSTRAINT operations_workflow_selection_pair
  CHECK ((workflow_code IS NULL) = (workflow_version IS NULL));

CREATE OR REPLACE FUNCTION prevent_operation_workflow_selection_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF OLD.workflow_code IS NOT NULL
    AND (NEW.workflow_code IS DISTINCT FROM OLD.workflow_code
      OR NEW.workflow_version IS DISTINCT FROM OLD.workflow_version) THEN
    RAISE EXCEPTION 'operation workflow selection is immutable' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS operations_workflow_selection_immutable ON operations;
CREATE TRIGGER operations_workflow_selection_immutable
BEFORE UPDATE OF workflow_code, workflow_version ON operations
FOR EACH ROW EXECUTE FUNCTION prevent_operation_workflow_selection_mutation();

CREATE OR REPLACE FUNCTION prevent_event_workflow_selection_mutation()
RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  IF NEW.workflow_code IS DISTINCT FROM OLD.workflow_code
    OR NEW.workflow_version IS DISTINCT FROM OLD.workflow_version THEN
    RAISE EXCEPTION 'event workflow selection is immutable' USING ERRCODE = 'check_violation';
  END IF;
  RETURN NEW;
END;
$$;
DROP TRIGGER IF EXISTS events_workflow_selection_immutable ON events;
CREATE TRIGGER events_workflow_selection_immutable
BEFORE UPDATE OF workflow_code, workflow_version ON events
FOR EACH ROW EXECUTE FUNCTION prevent_event_workflow_selection_mutation();

